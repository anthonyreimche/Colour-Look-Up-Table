/** The struct is six float[49] arrays and an int32: 1180 bytes. */
const STRUCT_BYTES = 6 * MAX_PATCHES * 4 + 4;

/** dt_exif_xmp_decode on plain hex, then the struct read as darktable lays
 *  it out. */
export function decodeParams(hex: string): Params {
  if (hex.length !== 2 * STRUCT_BYTES) throw new Error(`expected ${2 * STRUCT_BYTES} hex digits, got ${hex.length}`);
  const view = new DataView(new ArrayBuffer(STRUCT_BYTES));
  for (let i = 0; i < STRUCT_BYTES; i++) view.setUint8(i, parseInt(hex.slice(2 * i, 2 * i + 2), 16));
  const array = (k: number) => Array.from({ length: MAX_PATCHES }, (_, i) => view.getFloat32(4 * (k * MAX_PATCHES + i), true));
  const [sL, sa, sb, tL, ta, tb] = [0, 1, 2, 3, 4, 5].map(array);
  const count = Math.min(MAX_PATCHES, Math.max(0, view.getInt32(6 * MAX_PATCHES * 4, true)));
  return {
    patches: Array.from({ length: count }, (_, k): Patch => ({ source: [sL[k], sa[k], sb[k]], target: [tL[k], ta[k], tb[k]] })),
  };
}

